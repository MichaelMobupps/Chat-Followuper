#!/usr/bin/env node
/**
 * Ticket prospect-multi-format-upload — patch 1/2:
 *   create artifacts/dashboard/src/lib/parse-uploaded-urls.ts
 *
 * The new helper takes a File and returns extracted URLs regardless
 * of source format. Dispatch on file extension:
 *   - txt / csv / tsv: read as text
 *   - xlsx / xls:      parse with SheetJS, sheet_to_csv each sheet
 *   - other:           fall back to text, warn
 *
 * URLs are extracted by regex from whatever text the parser produced.
 * This means CSV column structure does not matter; URLs in any column
 * (or in headers, or in cells alongside other content) are captured.
 *
 * Trailing punctuation (.,;:!?)]) is stripped from matches because
 * URLs in prose often end with sentence-ending punctuation.
 *
 * Idempotent. If the file already exists with matching content, SKIP.
 * If it exists with our marker but different content (drift), SKIP.
 * If it exists with unrelated content, FAIL (do not overwrite).
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

const FILE = resolve(
  process.cwd(),
  "artifacts/dashboard/src/lib/parse-uploaded-urls.ts",
);

const CONTENT = `// AUTO-GENERATED by ticket-prospect-multi-format-upload.
// parseUploadedUrls — extract URLs from txt/csv/tsv/xlsx/xls files.
//
// Dispatches on file extension. Text formats are read directly; xlsx
// and xls are parsed via SheetJS, with each sheet converted to CSV
// before regex-extraction. Returns deduplicated URLs in first-seen
// order plus any warnings to surface to the user.

import * as XLSX from "xlsx";

const URL_RE = /https?:\\/\\/[^\\s,;|"'<>{}]+/g;
const TRAILING_PUNCT_RE = /[.,;:!?)\\]>]+$/;

export interface ParseUploadedUrlsResult {
  urls: string[];
  warnings: string[];
}

export async function parseUploadedUrls(
  file: File,
): Promise<ParseUploadedUrlsResult> {
  const ext = (file.name.split(".").pop() ?? "").toLowerCase();
  const warnings: string[] = [];
  let text: string;

  switch (ext) {
    case "txt":
    case "csv":
    case "tsv": {
      text = await file.text();
      break;
    }
    case "xlsx":
    case "xls": {
      try {
        const buf = await file.arrayBuffer();
        const wb = XLSX.read(buf, { type: "array" });
        text = wb.SheetNames.map((name) =>
          XLSX.utils.sheet_to_csv(wb.Sheets[name] ?? {}),
        ).join("\\n");
      } catch (err) {
        const msg = err instanceof Error ? err.message : String(err);
        return {
          urls: [],
          warnings: [\`Could not read \${file.name}: \${msg}\`],
        };
      }
      break;
    }
    default: {
      // Unknown extension. Best-effort: try as text. Warn user.
      try {
        text = await file.text();
        warnings.push(
          \`Unknown file extension ".\${ext}" in \${file.name}; read as plain text. Supported: .txt, .csv, .tsv, .xlsx, .xls.\`,
        );
      } catch (err) {
        const msg = err instanceof Error ? err.message : String(err);
        return {
          urls: [],
          warnings: [\`Could not read \${file.name}: \${msg}\`],
        };
      }
    }
  }

  const matches = text.match(URL_RE) ?? [];
  const cleaned = matches.map((u) => u.replace(TRAILING_PUNCT_RE, ""));

  const seen = new Set<string>();
  const unique: string[] = [];
  for (const u of cleaned) {
    if (!seen.has(u)) {
      seen.add(u);
      unique.push(u);
    }
  }

  if (unique.length === 0) {
    warnings.push(
      \`No URLs found in \${file.name}. The file is supported but contained no http(s) URLs.\`,
    );
  }

  return { urls: unique, warnings };
}
`;

const MARKER = "AUTO-GENERATED by ticket-prospect-multi-format-upload";

function main() {
  if (existsSync(FILE)) {
    const existing = readFileSync(FILE, "utf8");
    if (existing === CONTENT) {
      console.log("[parse-urls-helper] SKIP — file matches desired content");
      return 0;
    }
    if (existing.includes(MARKER)) {
      console.log("[parse-urls-helper] SKIP — file has our marker (drift OK, will not overwrite)");
      return 0;
    }
    console.log("[parse-urls-helper] FAIL — file exists with unrelated content");
    return 2;
  }

  mkdirSync(dirname(FILE), { recursive: true });
  writeFileSync(FILE, CONTENT, "utf8");
  console.log("[parse-urls-helper] APPLY — created file");

  // Re-read and verify
  const written = readFileSync(FILE, "utf8");
  const evidence = {
    fileExists: existsSync(FILE),
    hasMarker: written.includes(MARKER),
    hasFunction: written.includes("export async function parseUploadedUrls"),
    hasSheetjsImport: written.includes(`import * as XLSX from "xlsx"`),
    hasUrlRegex: written.includes("const URL_RE ="),
    hasReturnType: written.includes("Promise<ParseUploadedUrlsResult>"),
  };
  console.log("[parse-urls-helper] [evidence]", JSON.stringify(evidence));
  if (Object.values(evidence).some((v) => !v)) {
    console.log("[parse-urls-helper] FAIL — evidence check failed");
    return 4;
  }
  console.log("[parse-urls-helper] DONE");
  return 0;
}

process.exit(main());
